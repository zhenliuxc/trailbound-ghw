import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sharp = require('/Users/liuxucheng/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = path.join(root, 'art/characters/walk-source-v2.png');
const output = path.join(root, 'dist/characters/trailbound-walk-v2.webp');
const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const columnEdges = [0, 443, 887, 1330, 1774];
const rowEdges = [0, 447, 887];
const hipAxes = [265, 690, 1120, 1550, 285, 705, 1120, 1550];
const poses = ['left-contact', 'left-weight', 'right-pass', 'right-rise', 'right-contact', 'right-weight', 'left-pass', 'left-rise'];
const alphaThreshold = 12;

const frames = poses.map((pose, index) => {
  const column = index % 4;
  const row = Math.floor(index / 4);
  const cell = {
    x: columnEdges[column], y: rowEdges[row],
    width: columnEdges[column + 1] - columnEdges[column],
    height: rowEdges[row + 1] - rowEdges[row],
  };
  const visited = new Uint8Array(cell.width * cell.height);
  const components = [];
  const hasAlpha = (x, y) => data[((cell.y + y) * info.width + cell.x + x) * 4 + 3] > alphaThreshold;

  for (let y = 0; y < cell.height; y++) {
    for (let x = 0; x < cell.width; x++) {
      const start = y * cell.width + x;
      if (visited[start] || !hasAlpha(x, y)) continue;
      visited[start] = 1;
      const queue = [start];
      let cursor = 0, minX = x, minY = y, maxX = x, maxY = y;
      while (cursor < queue.length) {
        const pixel = queue[cursor++];
        const px = pixel % cell.width;
        const py = Math.floor(pixel / cell.width);
        minX = Math.min(minX, px); minY = Math.min(minY, py);
        maxX = Math.max(maxX, px); maxY = Math.max(maxY, py);
        for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            const nx = px + dx, ny = py + dy;
            if (nx < 0 || nx >= cell.width || ny < 0 || ny >= cell.height) continue;
            const next = ny * cell.width + nx;
            if (visited[next] || !hasAlpha(nx, ny)) continue;
            visited[next] = 1;
            queue.push(next);
          }
        }
      }
      components.push({ pixels: queue.length, minX, minY, maxX, maxY });
    }
  }

  components.sort((a, b) => b.pixels - a.pixels);
  const body = components[0];
  const visibleBounds = {
    x: cell.x + body.minX, y: cell.y + body.minY,
    width: body.maxX - body.minX + 1, height: body.maxY - body.minY + 1,
  };
  const left = Math.max(cell.x, visibleBounds.x - 1);
  const top = Math.max(cell.y, visibleBounds.y - 1);
  const right = Math.min(cell.x + cell.width, visibleBounds.x + visibleBounds.width + 1);
  const bottom = Math.min(cell.y + cell.height, visibleBounds.y + visibleBounds.height + 1);
  const sourceRect = { x: left, y: top, width: right - left, height: bottom - top };
  const footAnchorSource = { x: hipAxes[index], y: visibleBounds.y + visibleBounds.height };
  const footAnchor = { x: footAnchorSource.x - sourceRect.x, y: footAnchorSource.y - sourceRect.y };
  return { index, pose, cellRect: cell, visibleBounds, sourceRect, footAnchorSource, footAnchor };
});

const heights = frames.map(frame => frame.visibleBounds.height).sort((a, b) => a - b);
const medianVisibleHeight = (heights[3] + heights[4]) / 2;
const scale = 54 / medianVisibleHeight;
const metadata = {
  image: '/characters/trailbound-walk-v2.webp',
  source: 'art/characters/walk-source-v2.png',
  width: info.width, height: info.height, columns: 4, rows: 2,
  columnEdges, rowEdges, alphaThreshold, medianVisibleHeight,
  mapVisibleHeight: 54, mapScale: scale,
  coordinates: 'cellRect, visibleBounds, sourceRect and footAnchorSource use source-image coordinates. footAnchor is relative to sourceRect.',
  bounds: 'Largest eight-connected alpha > 12 component per cell. sourceRect adds one pixel within the cell. No source pixels are changed.',
  frames,
};
const tuples = frames.map(({ sourceRect: rect, footAnchor: foot }) =>
  `  [${rect.x}, ${rect.y}, ${rect.width}, ${rect.height}, ${foot.x}, ${foot.y}],`).join('\n');
const typescript = `// Generated by art/characters/walk-prepare-v2.mjs. Edit the source asset or preparation script.\n\nexport const MAP_WALK_FILE = 'characters/trailbound-walk-v2.webp';\nexport const MAP_WALK_WIDTH = ${info.width};\nexport const MAP_WALK_HEIGHT = ${info.height};\nexport const MAP_WALK_SCALE = 54 / ${medianVisibleHeight};\n\nexport type MapWalkFrame = readonly [\n  sourceX: number, sourceY: number, width: number, height: number, footX: number, footY: number,\n];\n\nexport const MAP_WALK_FRAMES: readonly MapWalkFrame[] = [\n${tuples}\n];\n`;

await sharp(source).webp({ quality: 90, alphaQuality: 100, effort: 6 }).toFile(output);
await fs.writeFile(path.join(root, 'art/characters/walk-v2.json'), JSON.stringify(metadata, null, 2) + '\n');
await fs.writeFile(path.join(root, 'src/runtime/map-walk-art.ts'), typescript);
