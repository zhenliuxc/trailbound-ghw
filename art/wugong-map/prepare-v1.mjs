import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const directory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(directory, '../..');
const propsSource = path.join(directory, 'props-source-v1.png');
const terrainSource = path.join(directory, 'terrain-source-v1.png');
const { data, info } = await sharp(propsSource).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const alphaThreshold = 12;
const sourceRegions = [
  { name: 'tree', x: 0, y: 0, width: 657, height: 770, footX: 337, footY: 720 },
  { name: 'grass', x: 657, y: 0, width: 597, height: 770, footX: 946, footY: 693 },
  { name: 'camp', x: 0, y: 770, width: 657, height: 484, footX: 326, footY: 1150 },
  { name: 'rock', x: 657, y: 770, width: 597, height: 484, footX: 947, footY: 1193 },
];

function componentsIn(region, pixels = data, sourceWidth = info.width) {
  const total = region.width * region.height;
  const visited = new Uint8Array(total);
  const queue = new Int32Array(total);
  const components = [];
  const hasAlpha = (x, y) => pixels[((region.y + y) * sourceWidth + region.x + x) * 4 + 3] > alphaThreshold;
  for (let y = 0; y < region.height; y++) {
    for (let x = 0; x < region.width; x++) {
      const start = y * region.width + x;
      if (visited[start] || !hasAlpha(x, y)) continue;
      visited[start] = 1;
      let read = 0, end = 0, minX = x, minY = y, maxX = x, maxY = y;
      queue[end++] = start;
      while (read < end) {
        const pixel = queue[read++];
        const px = pixel % region.width;
        const py = Math.floor(pixel / region.width);
        minX = Math.min(minX, px); maxX = Math.max(maxX, px);
        minY = Math.min(minY, py); maxY = Math.max(maxY, py);
        for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            const nx = px + dx, ny = py + dy;
            if (nx < 0 || nx >= region.width || ny < 0 || ny >= region.height) continue;
            const next = ny * region.width + nx;
            if (visited[next] || !hasAlpha(nx, ny)) continue;
            visited[next] = 1;
            queue[end++] = next;
          }
        }
      }
      components.push({ pixels: end, minX, minY, maxX, maxY });
    }
  }
  return components.sort((a, b) => b.pixels - a.pixels);
}

const props = Object.fromEntries(sourceRegions.map(region => {
  const components = componentsIn(region);
  const largest = components[0];
  if (!largest) throw new Error('No visible prop: ' + region.name);
  const main = components.filter(component => component.pixels >= largest.pixels * 0.008);
  const minX = region.x + Math.min(...main.map(component => component.minX));
  const minY = region.y + Math.min(...main.map(component => component.minY));
  const maxX = region.x + Math.max(...main.map(component => component.maxX));
  const maxY = region.y + Math.max(...main.map(component => component.maxY));
  const x = Math.max(region.x, minX - 6);
  const y = Math.max(region.y, minY - 6);
  const right = Math.min(region.x + region.width, maxX + 7);
  const bottom = Math.min(region.y + region.height, maxY + 7);
  return [region.name, {
    x, y, width: right - x, height: bottom - y,
    footX: region.footX - x, footY: region.footY - y,
  }];
}));

const entries = Object.entries(props).map(([name, prop]) => '  ' + name + ': ' + JSON.stringify(prop) + ',').join('\n');
const typescript = `// Generated by art/wugong-map/prepare-v1.mjs. Source rectangles and anchors use source pixels.\n\nexport const WUGONG_PROP_FILE = 'sprites/wugong-map-props-v1.webp';\nexport const WUGONG_PROP_WIDTH = ${info.width};\nexport const WUGONG_PROP_HEIGHT = ${info.height};\n\nexport type WugongPropArt = Readonly<{\n  x: number; y: number; width: number; height: number; footX: number; footY: number;\n}>;\n\nexport const WUGONG_PROPS = {\n${entries}\n} satisfies Record<string, WugongPropArt>;\n`;
await sharp(terrainSource).webp({ quality: 90, effort: 6 }).toFile(path.join(root, 'dist/scenes/wugong-terrain-v1.webp'));
await sharp(propsSource).webp({ quality: 90, alphaQuality: 100, effort: 6 }).toFile(path.join(root, 'dist/sprites/wugong-map-props-v1.webp'));
await fs.writeFile(path.join(root, 'src/runtime/wugong-prop-art.ts'), typescript);
await fs.writeFile(path.join(directory, 'props-v1.json'), JSON.stringify({
  image: 'sprites/wugong-map-props-v1.webp', source: 'art/wugong-map/props-source-v1.png',
  width: info.width, height: info.height, alphaThreshold, sourceRegions, props,
  bounds: 'Eight-connected alpha > 12 components. Union all components at least 0.8% of the largest per explicitly separated region; add six transparent pixels within its region. Pixels stay unchanged.',
  anchors: 'footX and footY in props are relative to the source rectangle. sourceRegions foot anchors are manually read ground-contact points in the complete source image.',
  processing: 'Whole-image WebP encoding only; preserve original generated alpha. No repainting, masks, background replacement, resize, or source-pixel edits.',
}, null, 2) + '\n');
console.log(JSON.stringify({ width: info.width, height: info.height, props }, null, 2));

const restSource = path.join(directory, 'hiker-rest-source-v1.png');
const rest = await sharp(restSource).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const restRegions = [
  { name: 'sit', x: 0, y: 0, width: 887, height: 887, footX: 622, footY: 812 },
  { name: 'view', x: 887, y: 0, width: 887, height: 887, footX: 1408, footY: 815 },
];
const frames = restRegions.map(region => {
  const main = componentsIn(region, rest.data, rest.info.width)[0];
  if (!main) throw new Error('No visible rest pose: ' + region.name);
  const visibleBounds = {
    x: region.x + main.minX, y: region.y + main.minY,
    width: main.maxX - main.minX + 1, height: main.maxY - main.minY + 1,
  };
  const x = Math.max(region.x, visibleBounds.x - 6);
  const y = Math.max(region.y, visibleBounds.y - 6);
  const right = Math.min(region.x + region.width, visibleBounds.x + visibleBounds.width + 6);
  const bottom = Math.min(region.y + region.height, visibleBounds.y + visibleBounds.height + 6);
  return {
    name: region.name, cellRect: { x: region.x, y: region.y, width: region.width, height: region.height },
    visibleBounds, sourceRect: { x, y, width: right - x, height: bottom - y },
    footAnchorSource: { x: region.footX, y: region.footY },
    footAnchor: { x: region.footX - x, y: region.footY - y },
  };
});
await sharp(restSource).webp({ quality: 90, alphaQuality: 100, effort: 6 }).toFile(path.join(root, 'dist/characters/wugong-rest-view-v1.webp'));
await fs.writeFile(path.join(directory, 'hiker-rest-v1.json'), JSON.stringify({
  image: 'characters/wugong-rest-view-v1.webp', source: 'art/wugong-map/hiker-rest-source-v1.png',
  width: rest.info.width, height: rest.info.height, columns: 2, rows: 1, alphaThreshold, frames,
  bounds: 'Largest eight-connected alpha > 12 component per equal-width cell, with six-pixel sourceRect padding within the cell.',
  processing: 'Whole-image WebP encoding only, original alpha and source pixels preserved; no resize, recolor or repainting.',
}, null, 2) + '\n');
const restEntries = frames.map(({ name, sourceRect, footAnchor }) => '  ' + name + ': ' + JSON.stringify({
  ...sourceRect, footX: footAnchor.x, footY: footAnchor.y,
}) + ',').join('\n');
await fs.writeFile(path.join(root, 'src/runtime/wugong-rest-art.ts'), `// Generated by art/wugong-map/prepare-v1.mjs. Source rectangles and anchors use source pixels.\n\nexport const WUGONG_REST_FILE = 'characters/wugong-rest-view-v1.webp';\nexport const WUGONG_REST_WIDTH = ${rest.info.width};\nexport const WUGONG_REST_HEIGHT = ${rest.info.height};\n\nexport type WugongRestArt = Readonly<{\n  x: number; y: number; width: number; height: number; footX: number; footY: number;\n}>;\n\nexport const WUGONG_REST_FRAMES = {\n${restEntries}\n} satisfies Record<string, WugongRestArt>;\n`);
const manifestEntries = [];
for (const [file, source] of [
  ['scenes/wugong-terrain-v1.webp', 'terrain-source-v1.png'],
  ['sprites/wugong-map-props-v1.webp', 'props-source-v1.png'],
  ['characters/wugong-rest-view-v1.webp', 'hiker-rest-source-v1.png'],
]) {
  const bytes = await fs.readFile(path.join(root, 'dist', file));
  const original = await fs.readFile(path.join(directory, source));
  const metadata = await sharp(bytes).metadata();
  manifestEntries.push({ file, source: 'art/wugong-map/' + source, width: metadata.width, height: metadata.height,
    bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'),
    sourceSha256: createHash('sha256').update(original).digest('hex') });
}
await fs.writeFile(path.join(root, 'dist/scenes/wugong-map-v1.json'), JSON.stringify({
  generator: 'built-in imagegen', processing: 'Whole-image WebP encoding; original aspect, pixels and alpha preserved.',
  promptRecord: 'art/wugong-map/README.md', entries: manifestEntries,
}, null, 2) + '\n');
console.log(JSON.stringify({ width: rest.info.width, height: rest.info.height, frames, assets: manifestEntries.map(entry => entry.file) }, null, 2));
