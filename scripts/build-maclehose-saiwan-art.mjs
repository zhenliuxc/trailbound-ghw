import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'art/maclehose-saiwan-steps-v13');
const output = resolve(root, 'public/scenes/maclehose-saiwan-v13');
await mkdir(output, { recursive: true });
const frames = {}, records = [];
for (const name of ['panorama', 'terrain', 'shoulder', 'blue-poses', 'braids-poses']) {
  const bytes = await readFile(resolve(source, name + '.png'));
  const image = sharp(bytes), metadata = await image.metadata();
  const encoded = await image.webp({ quality: 92, alphaQuality: 100 }).toBuffer();
  await writeFile(resolve(output, name + '.webp'), encoded);
  records.push({ file: `scenes/maclehose-saiwan-v13/${name}.webp`, width: metadata.width, height: metadata.height, alpha: metadata.hasAlpha,
    bytes: encoded.length, sha256: createHash('sha256').update(encoded).digest('hex'), sourceSha256: createHash('sha256').update(bytes).digest('hex') });
  if (!name.endsWith('-poses')) continue;
  const { data, info } = await sharp(bytes).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const poses = [];
  for (let index = 0; index < 8; index++) {
    const left = Math.floor(index % 4 * info.width / 4), right = Math.floor((index % 4 + 1) * info.width / 4);
    const top = Math.floor(Math.floor(index / 4) * info.height / 2), bottom = Math.floor((Math.floor(index / 4) + 1) * info.height / 2);
    let x0 = right, x1 = left, y0 = bottom, y1 = top;
    for (let y = top; y < bottom; y++) for (let x = left; x < right; x++) if (data[(y * info.width + x) * 4 + 3] > 48) {
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
    if (x1 <= x0 || y1 <= y0) throw new Error(`Missing pose ${name}:${index}`);
    x0 = Math.max(left, x0 - 3); x1 = Math.min(right - 1, x1 + 3); y0 = Math.max(top, y0 - 3); y1 = Math.min(bottom - 1, y1 + 3);
    const width = x1 - x0 + 1, height = y1 - y0 + 1;
    const landing = index === 1 || index === 3, contactLeft = landing ? Math.floor(x0 + width * .62) : x0;
    let contactY = y1 - 3;
    if (landing) {
      contactY = y0;
      for (let y = Math.floor(y0 + height * .65); y <= y1; y++) for (let x = contactLeft; x <= x1; x++) if (data[(y * info.width + x) * 4 + 3] > 180) contactY = y;
    }
    let weight = 0, foot = 0;
    for (let y = Math.max(y0, contactY - 7); y <= contactY; y++) for (let x = contactLeft; x <= x1; x++) {
      const alpha = data[(y * info.width + x) * 4 + 3]; if (alpha > 180) { foot += x * alpha; weight += alpha; }
    }
    poses.push({ x: x0, y: y0, width, height, footX: index >= 5 ? width * .63 : (weight ? foot / weight : (x0 + x1) / 2) - x0, footY: contactY - y0 });
  }
  frames[name.startsWith('blue') ? 'blue' : 'braids'] = poses;
}
const code = `// Generated by scripts/build-maclehose-saiwan-art.mjs.\nimport type { CharacterFrame } from '../../../characters/catalog';\nexport const SHOULDER_POSES = ${JSON.stringify(frames, null, 2)} satisfies Record<'blue' | 'braids', readonly Omit<CharacterFrame, 'scale' | 'contactX'>[]>;\n`;
await writeFile(resolve(root, 'src/runtime/coast-memories/shoulder/pose-art.generated.ts'), code);
await writeFile(resolve(output, 'credits.json'), JSON.stringify({ tool: 'built-in image_gen', generation: 'art/maclehose-saiwan-steps-v13/generation.json',
  geographicReference: { author: 'rheins', title: '大浪湾 - Tai Long Wan - 2015.01 - panoramio.jpg', source: 'https://commons.wikimedia.org/wiki/File:%E5%A4%A7%E6%B5%AA%E6%B9%BE_-_Tai_Long_Wan_-_2015.01_-_panoramio.jpg', license: 'CC BY 3.0', licenseUrl: 'https://creativecommons.org/licenses/by/3.0/' },
  description: '艺术化西湾山山海与阶路、两位既有 Q 版旅人的上阶和停留姿态。不是实景复原。',
  processing: '原生尺寸 WebP 编码，保留透明通道；图集按四列两行扫描可见边界并记录落脚锚点。没有插值放大或声称原生 4K。', assets: records }, null, 2) + '\n');
