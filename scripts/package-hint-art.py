"""Crop and encode the original transparent hint artwork, without repainting it."""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('source', type=Path)
args = parser.parse_args()
original = Image.open(args.source).convert('RGBA')
visible = original.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
if visible is None:
    raise ValueError('The hint artwork has no visible pixels')
box = (max(0, visible[0] - 6), max(0, visible[1] - 6),
       min(original.width, visible[2] + 6), min(original.height, visible[3] + 6))
image = original.crop(box)
image.thumbnail((384, 160), Image.Resampling.LANCZOS)
alpha = image.getchannel('A')
for x in range(image.width - 1, -1, -1):
    ys = [y for y in range(image.height) if alpha.getpixel((x, y)) > 128]
    if ys:
        tip = {'x': x / image.width, 'y': sum(ys) / len(ys) / image.height}
        break
file = 'sprites/hint-brush-v1.webp'
output = root / 'public' / file
image.save(output, 'WEBP', quality=92, method=6)
asset = {'file': file, 'width': image.width, 'height': image.height, 'tip': tip}
manifest = {**asset, 'generator': 'OpenAI ImageGen', 'source': str(args.source),
            'sourceSize': list(original.size), 'sourceCrop': list(box),
            'sourceSha256': hashlib.sha256(args.source.read_bytes()).hexdigest(),
            'sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
            'bytes': output.stat().st_size,
            'processing': 'Trim transparent margins, uniform resize and WebP encoding only; original alpha preserved.'}
(root / 'public/sprites/hint-brush-v1.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
(root / 'src/runtime/hint-asset.ts').write_text(
    '// Generated by scripts/package-hint-art.py; do not repaint or stretch the source.\n'
    + 'export const HINT_ART = ' + json.dumps(asset, ensure_ascii=False, indent=2) + ' as const;\n')
print(json.dumps({'file': file, 'width': image.width, 'height': image.height,
                  'tip': tip, 'bytes': output.stat().st_size}))
