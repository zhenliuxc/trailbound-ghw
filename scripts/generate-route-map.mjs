import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { geoArea, geoConicConformal, geoContains, geoPath } from 'd3-geo';

const root = new URL('../', import.meta.url);
const source = JSON.parse(await readFile(new URL('assets/maps/china-overview.geojson', root), 'utf8'));
const locations = JSON.parse(await readFile(new URL('assets/maps/route-locations.json', root), 'utf8'));
const physical = JSON.parse(await readFile(new URL('assets/maps/china-physical.geojson', root), 'utf8'));

// D3's spherical polygons use clockwise exterior rings. Normalize each polygon,
// including its holes, without changing the stored source geography.
function polygon(rings) {
  return geoArea({ type: 'Polygon', coordinates: rings }) > Math.PI * 2
    ? rings.map(ring => [...ring].reverse()) : rings;
}
const land = {
  type: 'FeatureCollection',
  features: source.features.map(feature => ({ ...feature, geometry: {
    ...feature.geometry,
    coordinates: feature.geometry.type === 'MultiPolygon'
      ? feature.geometry.coordinates.map(polygon) : polygon(feature.geometry.coordinates),
  } })),
};
const projection = geoConicConformal().parallels([25, 47]).rotate([-105, 0]).precision(.25)
  .fitExtent([[24, 24], [936, 596]], land);
const project = ([longitude, latitude]) => {
  const point = projection([longitude, latitude]);
  if (!point) throw new Error('路线位置无法投影');
  return { x: +point[0].toFixed(2), y: +point[1].toFixed(2) };
};
const path = geoPath(projection).digits(1);
const relief = [], rivers = [];
for (const feature of physical.features) {
  if (feature.geometry.type === 'LineString' || feature.geometry.type === 'MultiLineString') {
    rivers.push(path(feature));
    continue;
  }
  const normalized = { ...feature, geometry: { ...feature.geometry, coordinates: feature.geometry.type === 'MultiPolygon'
    ? feature.geometry.coordinates.map(polygon) : polygon(feature.geometry.coordinates) } };
  const kind = feature.properties.kind === 'Range/mtn' ? 'mountain' : feature.properties.kind === 'Plateau' ? 'plateau' : 'basin';
  const [[left, top], [right, bottom]] = path.bounds(normalized);
  let marks = '';
  if (kind === 'mountain') {
    for (let y = Math.ceil(top / 13) * 13; y < bottom; y += 13) {
      for (let x = Math.ceil(left / 14) * 14 + (Math.round(y / 13) % 2) * 7; x < right; x += 14) {
        const point = projection.invert([x, y]);
        if (point && geoContains(normalized, point)) marks += `M${x-4},${y+2}l4,-5l4,5m-4,-5l1,4`;
      }
    }
  }
  relief.push({ kind, path: path(normalized), marks });
}
const geometry = {
  width: 960, height: 620,
  bounds: path.bounds(land),
  landPath: path(land), relief, rivers,
  labels: [
    { name: '青藏高原', at: [88, 32.7], kind: 'land' },
    { name: '塔里木盆地', at: [82.5, 39.7], kind: 'land' },
    { name: '天山', at: [86, 43.6], kind: 'land' },
    { name: '东海', at: [126, 29], kind: 'sea' },
    { name: '南海', at: [116, 19.5], kind: 'sea' },
  ].map(({ at, ...label }) => ({ ...label, ...project(at) })),
  anchors: Object.fromEntries(Object.entries(locations).map(([id, point]) => [id, project(point)])),
};
const target = new URL('src/runtime/route-map-geometry.generated.ts', root);
await writeFile(target, `// Generated by scripts/generate-route-map.mjs. Source: Natural Earth (public domain).\nimport type { RouteId } from './contracts';\n\nexport const ROUTE_MAP_GEOMETRY = ${JSON.stringify(geometry)} satisfies {\n  width: number; height: number; landPath: string; bounds: [[number, number], [number, number]];\n  relief: readonly { kind: 'mountain' | 'plateau' | 'basin'; path: string; marks: string }[];\n  rivers: readonly string[];\n  labels: readonly { name: string; kind: 'land' | 'sea'; x: number; y: number }[];\n  anchors: Record<RouteId, { readonly x: number; readonly y: number }>;\n};\n`);
process.stdout.write(`Generated ${fileURLToPath(target)}\n`);
