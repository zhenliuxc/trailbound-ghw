import fs from 'node:fs/promises';
import sharp from 'sharp';

const root=new URL('../../',import.meta.url), source=new URL('art/aotai-painterly-v1/',root), output=new URL('public/scenes/aotai-painterly-v1/',root);
await fs.mkdir(output,{recursive:true});
for(const name of ['stone-sea','ridge','winter-encounter','winter-slope','props-atlas']){
 await sharp(await fs.readFile(new URL(`${name}.png`,source))).webp({quality:91,alphaQuality:100}).toFile(new URL(`${name}.webp`,output).pathname);
}
const {data,info}=await sharp(await fs.readFile(new URL('props-atlas.png',source))).ensureAlpha().raw().toBuffer({resolveWithObject:true});
function bounds(region){
 const left=Math.floor(region[0]*info.width),top=Math.floor(region[1]*info.height),right=Math.floor(region[2]*info.width),bottom=Math.floor(region[3]*info.height);
 let x0=right,y0=bottom,x1=left,y1=top;
 for(let y=top;y<bottom;y++)for(let x=left;x<right;x++)if(data[(y*info.width+x)*4+3]>32){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
 if(x1<=x0||y1<=y0)throw Error('Missing painted prop in its atlas region');
 x0=Math.max(left,x0-3);y0=Math.max(top,y0-3);x1=Math.min(right-1,x1+3);y1=Math.min(bottom-1,y1+3);
 return {x:x0,y:y0,width:x1-x0+1,height:y1-y0+1};
}
const frames={mother:bounds([0,0,.61,.541]),calf:bounds([.64,0,1,.541]),tent:bounds([0,.542,.65,1]),snowball:bounds([.7,.59,1,1])};
await fs.writeFile(new URL('src/runtime/aotai-games/painterly-art.ts',root),`// Generated by scripts/art/prepare-aotai-painterly.mjs. Visible alpha bounds, no animation state.\nexport const PAINTED_PROPS_FILE = 'scenes/aotai-painterly-v1/props-atlas.webp';\nexport const PAINTED_PROPS = ${JSON.stringify(frames,null,2)};\n`);
