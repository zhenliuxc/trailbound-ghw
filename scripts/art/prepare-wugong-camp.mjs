import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';

const root = new URL('../../', import.meta.url);
const file = relative => new URL(relative, root);
await mkdir(file('dist/scenes/wugong-camp-night-v1/'), { recursive: true });
await sharp(file('art/wugong-camp-night/night-source-v1.png').pathname).webp({ quality: 86 }).toFile(file('dist/scenes/wugong-camp-night-v1/night-v1.webp').pathname);
const source = sharp(file('art/wugong-camp-night/actions-source-v1.png').pathname);
const { data, info } = await source.ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const rowCount = y => { let total = 0; for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3] > 80) total++; return total; };
let splitY = Math.floor(info.height / 2), count = Infinity;
for (let y = Math.floor(info.height * .46); y < info.height * .58; y++) { const occupied = rowCount(y); if (occupied < count) { count = occupied; splitY = y; } }
const splitX = Math.floor(info.width / 2), frames = [];
for (let index = 0; index < 4; index++) {
  const left = index % 2 ? splitX : 0, right = index % 2 ? info.width : splitX;
  const top = index < 2 ? 0 : splitY, bottom = index < 2 ? splitY : info.height;
  let x0 = right, y0 = bottom, x1 = left, y1 = top;
  for (let y = top; y < bottom; y++) for (let x = left; x < right; x++) {
    if (data[(y * info.width + x) * 4 + 3] < 80) continue;
    x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
  }
  x0 = Math.max(left, x0 - 3); y0 = Math.max(top, y0 - 3); x1 = Math.min(right - 1, x1 + 3); y1 = Math.min(bottom - 1, y1 + 3);
  const width = x1 - x0 + 1, height = y1 - y0 + 1, sole = index === 1 ? .32 : index === 0 ? .77 : .88;
  frames.push({ x: x0, y: y0, width, height, footX: width * sole, footY: height - 5 });
}
await source.webp({ lossless: true }).toFile(file('dist/scenes/wugong-camp-night-v1/actions-q-v1.webp').pathname);
await writeFile(file('src/wugong-walk/scroll/camp-poses.ts'), `// Generated by scripts/art/prepare-wugong-camp.mjs.\nexport const CAMP_POSE_FILE = 'scenes/wugong-camp-night-v1/actions-q-v1.webp';\nexport const CAMP_POSE_SCALE = 54 / ${frames[0].height};\nexport const CAMP_POSES = ${JSON.stringify(frames, null, 2)};\n`);
process.stdout.write(JSON.stringify({ width: info.width, height: info.height, splitY, frames }, null, 2) + '\n');
