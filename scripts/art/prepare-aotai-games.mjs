import fs from 'node:fs/promises';
import sharp from 'sharp';

const root = new URL('../../', import.meta.url);
const source = new URL('art/aotai-games-v2/', root);
const scenes = new URL('dist/scenes/aotai-games-v2/', root);
await fs.mkdir(scenes, { recursive: true });
for (const name of ['winter-tent', 'takin-atlas', 'winter-encounter', 'winter-slope']) {
  await sharp(await fs.readFile(new URL(`${name}.png`, source))).webp({ quality: 90, alphaQuality: 100 }).toFile(new URL(`${name}.webp`, scenes).pathname);
}
await sharp(await fs.readFile(new URL('camp-badge.png', source))).resize(640, 640).webp({ quality: 91, alphaQuality: 100 }).toFile(new URL('dist/badges/aotai-camp-night-v1.webp', root).pathname);

const { data, info } = await sharp(await fs.readFile(new URL('takin-atlas.png', source))).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const columns = Array.from({ length: info.width }, () => 0);
for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3] > 48) columns[x]++;
let split = Math.round(info.width * .63);
for (let x = Math.round(info.width * .6); x < Math.round(info.width * .68); x++) if (columns[x] < columns[split]) split = x;
function bounds(left, right) {
  let x0 = right, y0 = info.height, x1 = left, y1 = 0;
  for (let y = 0; y < info.height; y++) for (let x = left; x < right; x++) if (data[(y * info.width + x) * 4 + 3] > 16) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  x0 = Math.max(left, x0 - 5); y0 = Math.max(0, y0 - 5); x1 = Math.min(right - 1, x1 + 5); y1 = Math.min(info.height - 1, y1 + 5);
  return { x: x0, y: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };
}
const atlas = { mother: bounds(0, split), calf: bounds(split, info.width) };
await fs.writeFile(new URL('src/runtime/aotai-games/takin-art.ts', root), `// Generated by scripts/art/prepare-aotai-games.mjs from visible alpha bounds.\nexport const TAKIN_ATLAS = ${JSON.stringify(atlas, null, 2)};\n`);
console.log('Prepared watercolor assets and independent animal frames', atlas);
