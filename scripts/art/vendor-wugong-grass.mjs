import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = 'Steve245270533/three-stylized';
const revision = '8eb0dde5a8e7eae985d69f923b627b0cf253bed5';
const upstreamRepository = 'cortiz2894/stylized-components';
const upstreamRevision = '1cece0a296b29299d1380c34feb5c158b2f04500';
const root = fileURLToPath(new URL('../../', import.meta.url));
const destination = path.join(root, 'src/vendor/three-stylized');
const headers = { 'User-Agent': 'Trailbound-grass-study/1.0' };
const response = await fetch(`https://api.github.com/repos/${repository}/git/trees/${revision}?recursive=1`, { headers, signal: AbortSignal.timeout(25000) });
if (!response.ok) throw new Error(`Cannot read pinned grass source: ${response.status}`);
const inventory = await response.json();
const files = inventory.tree.filter(item => item.type === 'blob' && (item.path.startsWith('src/grass/') && item.path.endsWith('.ts') || item.path === 'LICENSE'));
const records = [];
await mkdir(destination, { recursive: true });
for (const entry of files) {
  const relative = entry.path === 'LICENSE' ? 'LICENSE' : entry.path.slice(4);
  const target = path.join(destination, relative);
  const source = `https://raw.githubusercontent.com/${repository}/${revision}/${entry.path}`;
  const result = await fetch(source, { headers, signal: AbortSignal.timeout(25000) });
  if (!result.ok) throw new Error(`Cannot download grass source ${entry.path}: ${result.status}`);
  const bytes = Buffer.from(await result.arrayBuffer());
  const blob = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
  if (blob !== entry.sha) throw new Error(`Source hash mismatch: ${entry.path}`);
  const existing = await readFile(target).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (existing && !existing.equals(bytes)) throw new Error(`Preserving an existing modified vendor file: ${target}`);
  await mkdir(path.dirname(target), { recursive: true });
  if (!existing) await writeFile(target, bytes);
  records.push({ path: relative, source, sha256: createHash('sha256').update(bytes).digest('hex') });
}
const upstreamSource = `https://raw.githubusercontent.com/${upstreamRepository}/${upstreamRevision}/LICENSE`;
const upstreamResult = await fetch(upstreamSource, { headers, signal: AbortSignal.timeout(25000) });
if (!upstreamResult.ok) throw new Error(`Cannot read the original component license: ${upstreamResult.status}`);
const upstreamBytes = Buffer.from(await upstreamResult.arrayBuffer());
const upstreamTarget = path.join(destination, 'UPSTREAM-LICENSE');
const existingUpstream = await readFile(upstreamTarget).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
if (existingUpstream && !existingUpstream.equals(upstreamBytes)) throw new Error('Preserving an existing modified original license.');
if (!existingUpstream) await writeFile(upstreamTarget, upstreamBytes);
records.push({ path: 'UPSTREAM-LICENSE', source: upstreamSource, sha256: createHash('sha256').update(upstreamBytes).digest('hex') });
await writeFile(path.join(destination, 'provenance.json'), `${JSON.stringify({ repository, revision, license: 'MIT', upstreamAttribution: 'Inspired by and adapted from cortiz2894/stylized-components', upstreamRepository, upstreamRevision, files: records }, null, 2)}\n`);
await writeFile(path.join(destination, 'ATTRIBUTION.txt'), `three-stylized\nhttps://github.com/${repository}\nRevision: ${revision}\nCopyright (c) 2026 Steve245270533. MIT License, see LICENSE.\nUpstream attribution: inspired by and adapted from https://github.com/cortiz2894/stylized-components\nOnly the grass module is included. No upstream install or build scripts are run.\n`);
process.stdout.write(`Saved ${records.length} pinned grass source files.\n`);
